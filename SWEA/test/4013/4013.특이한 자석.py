# 모든 자석의 회전이 끝난 후 획득하는 점수는 0 + 2 + 0 + 8 = 10 이 된다.
# 따라서, 이 예제의 정답은 10 이다.


# [제약사항]
# 1. 시간제한 : 최대 50 개 테스트 케이스를 모두 통과하는 데 C / C++ / Java 모두 3 초
# 2. 자석의 개수는 4 개이며, 각 자석은 8 개의 날을 가지고 있다.
# 3. 자석을 회전시키는 횟수 K 는 1 이상 20 이하의 정수이다. ( 1 ≤ K ≤ 20 )
# 4. 하나의 자석이 1 칸 회전될 때, 붙어 있는 자석은 서로 붙어 있는 날의 자성이 다를 경우에만 반대 방향으로 1 칸 회전된다.
# 5. 자석을 회전시키는 방향은 시계방향이 1 로, 반시계 방향이 -1 로 주어진다.
# 6. 날의 자성은 N 극이 0 으로, S 극이 1 로 주어진다.
# 7. 각 자석의 날 자성정보는 빨간색 화살표 위치의 날부터 시계방향 순서대로 주어진다.

# 예를 들어, [Fig. 1] 의 1 번 자석의 자성정보는 0 0 1 0 0 1 0 0 과 같이 주어진다.


# [입력]
# 입력의 맨 첫 줄에는 총 테스트 케이스의 개수 T 가 주어지고,
# 그 다음 줄부터 T 개의 테스트 케이스가 주어진다.
# 각 테스트 케이스의 첫 번째 줄에는 자석을 회전시키는 횟수 K 가 주어진다.
# 다음 4 개의 줄에는 1 번 자석부터 4 번 자석까지 각각 8 개 날의 자성정보가 차례대로 주어진다.
# 그 다음 K 개의 줄에는 자석을 1 칸씩 회전시키는 회전 정보가 주어진다.
# 자석의 회전 정보는 회전시키려는 자석의 번호, 회전방향으로 구성되어 있다.
# 회전방향은 1 일 경우 시계방향이며, -1 일 경우 반시계방향이다.


# [출력]
# 테스트 케이스 개수만큼 T 개의 줄에 각각의 테스트 케이스에 대한 답을 출력한다.
# 각 줄은 "#t" 로 시작하고 공백을 하나 둔 다음 정답을 출력한다. ( t 는 1 부터 시작하는 테스트 케이스의 번호이다. )
# 정답은 모든 자석의 회전이 끝난 후 획득한 점수의 총 합이다.


# import sys
# sys.stdin = open("/Users/tjddbsj/Desktop/github/algorithm/algorithm/SWEA/test/4013/sample_input.txt","r")
from collections import deque

# 테스트 케이스 개수 입력
T = int(input())

for tc in range(1, T + 1):
    # 회전 횟수 K 입력
    K = int(input())
    
    # 4개의 자석 정보를 deque로 저장 (인덱스: 0~3)
    magnet = [deque(map(int, input().split())) for _ in range(4)]
        
    for _ in range(K):
        # 회전시킬 자석 번호와 방향 입력
        idx, direction = map(int, input().split())
        idx -= 1  # 자석 번호(1~4)를 리스트 인덱스(0~3)로 변환
            
        # 이번 턴에 각 자석이 회전할 방향을 저장할 리스트 (0이면 회전 안 함)
        move = [0] * 4
        move[idx] = direction
            
        # 1. 기준 자석 기준 왼쪽 방향으로 연쇄 여부 확인
        for i in range(idx, 0, -1):
            # 왼쪽 자석의 오른쪽 날(인덱스 2)과 현재 자석의 왼쪽 날(인덱스 6) 비교
            if magnet[i-1][2] != magnet[i][6]:
                move[i-1] = -move[i] # 다르면 반대 방향으로 회전
            else:
                break # 자성이 같으면 더 이상 전파되지 않음
                    
        # 2. 기준 자석 기준 오른쪽 방향으로 연쇄 여부 확인
        for i in range(idx, 3):
            # 현재 자석의 오른쪽 날(인덱스 2)과 오른쪽 자석의 왼쪽 날(인덱스 6) 비교
            if magnet[i][2] != magnet[i+1][6]:
                move[i+1] = -move[i] # 다르면 반대 방향으로 회전
            else:
                break # 자성이 같으면 더 이상 전파되지 않음
            
        # 3. 모든 확인이 끝나면 결정된 방향대로 자석들을 한꺼번에 회전
        for i in range(4):
            if move[i] != 0:
                # deque.rotate(1)은 시계 방향, rotate(-1)은 반시계 방향
                magnet[i].rotate(move[i])
        
    # 모든 회전이 끝난 후 최종 점수 계산
    total_score = 0
    for i in range(4):
        if magnet[i][0] == 1: # 12시 방향(인덱스 0)이 S극(1)인 경우 점수 획득
            total_score += (2 ** i) # 1, 2, 4, 8점 순서
                
    print(f"#{tc} {total_score}")