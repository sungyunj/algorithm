# 게임은 핀볼이 출발 위치로 돌아오거나, 블랙홀에 빠질 때 끝나게 되며, 점수는 벽이나 블록에 부딪힌 횟수가 된다. (웜홀을 통과하는 것은 점수에 포함되지 않는다.)
# 블랙홀에 빠져서 게임이 끝나더라도, 벽이나 블록에 부딪혀 획득한 점수는 남아있게 된다.
# 게임판 위에서 출발 위치와 진행 방향을 임의로 선정가능 할 때,
# ▶ 게임에서 얻을 수 있는 점수의 최댓값을 구하여라!
# 단, 블록, 웜홀 또는 블랙홀이 있는 위치에서는 출발할 수 없다.

 
# [제약 사항]
# 게임판의 크기는 정사각형으로 주어지며, 한 변의 길이 N 은 5 이상 100 이하이다. (5 ≤ N ≤ 100)
# 웜홀은 게임판 내에서 숫자 6 ~ 10으로 주어진다.
# 블랙홀은 게임판 내에서 숫자 -1 로 주어진다.
# 게임판에서 웜홀 또는 블랙홀이 존재하지 않는 경우도 있다.
# 웜홀이 있는 경우 반드시 쌍(pair)으로 존재하며, 웜홀이 주어지는 경우 최대 5쌍 존재한다.
# 웜홀을 통과한 핀볼은 동일한 숫자를 가진 반대편 웜홀로 이동하게 되며, 이때 진행방향은 그대로 유지된다.
# 블랙홀은 최대 5개가 주어진다.
 

# [입력]
# 입력의 가장 첫 줄에는 총 테스트 케이스의 개수 T가 주어지며, 그 다음 줄부터 각 테스트 케이스가 주어진다.
# 각 테스트 케이스의 첫째 줄에는 N이 주어지고, 다음 N줄에 걸쳐서 핀볼 게임판의 모양이 주어진다.
# 게임판의 모양은 -1 이상 10 이하의 정수로 주어지며, 각 숫자는 한 칸씩 띄어져서 주어진다.
# 숫자에 따른 의미는 다음과 같다

 
# ------------------------------------------------------------------
# -1        0       1 ~ 5       6 ~ 10

# 블랙홀    빈공간      블록          웜홀
# ------------------------------------------------------------------
 

# [출력]
# 테스트 케이스 t에 대한 결과는 "#t"를 찍고, 한 칸 띄고 정답을 출력한다.
# (단, t는 테스트 케이스의 번호를 의미하며 1부터 시작한다.)




# 1. 방향 및 블록 테이블 정의
# 0:상, 1:하, 2:좌, 3:우
dx = [-1, 1, 0, 0]
dy = [0, 0, -1, 1]

# 반대 방향 전환용 (벽이나 5번 블록 충돌 시)
# 상(0)<->하(1), 좌(2)<->우(3)
opp = [1, 0, 3, 2]

# change_dir[블록번호][진입방향] = 꺾이는 방향
# 블록의 경사면을 만나면 90도 꺾이고, 평면을 만나면 반대(opp)로 나감
change_dir = [
    [],
    [1, 3, 0, 2], # 1번: 상->하, 하->우, 좌->상, 우->좌
    [3, 0, 1, 2], # 2번: 상->우, 하->상, 좌->하, 우->좌
    [2, 0, 3, 1], # 3번: 상->좌, 하->상, 좌->우, 우->하
    [1, 2, 3, 0], # 4번: 상->하, 하->좌, 좌->우, 우->상
    [1, 0, 3, 2]  # 5번: 전부 반대방향 (상<->하, 좌<->우)
]

T_str = input().strip()
if T_str:
    T = int(T_str)
    for tc in range(1, T + 1):
        N = int(input())
        board = [list(map(int, input().split())) for _ in range(N)]
        
        # 2. 웜홀 및 빈 공간 파악
        wormholes = [{} for _ in range(11)] # 6~10번 웜홀 위치 저장
        for r in range(N):
            for c in range(N):
                val = board[r][c]
                if val >= 6:
                    if (r, c) not in wormholes[val]:
                        # 웜홀은 쌍으로 존재하므로 발견될 때마다 추가
                        if "pair1" not in wormholes[val]:
                            wormholes[val]["pair1"] = (r, c)
                        else:
                            wormholes[val]["pair2"] = (r, c)

        max_score = 0

        # 3. 모든 격자 탐색
        for r in range(N):
            for c in range(N):
                if board[r][c] != 0: continue # 빈 공간에서만 출발 가능
                
                for d in range(4): # 4방향으로 시뮬레이션 시작
                    score = 0
                    curr_d = d
                    curr_r, curr_c = r, c
                    
                    while True:
                        nr = curr_r + dx[curr_d]
                        nc = curr_c + dy[curr_d]
                        
                        # A. 벽에 부딪히는 경우 (점수 +1, 방향 반대로)
                        if not (0 <= nr < N and 0 <= nc < N):
                            score += 1
                            curr_d = opp[curr_d]
                            curr_r, curr_c = nr, nc # 벽 밖 좌표에서 반대 방향으로 한 칸 이동 준비
                            continue

                        # B. 종료 조건: 블랙홀(-1)을 만나거나 시작 위치로 돌아온 경우
                        if (nr, nc) == (r, c) or board[nr][nc] == -1:
                            if score > max_score:
                                max_score = score
                            break
                        
                        # C. 블록(1~5)을 만나는 경우
                        if 1 <= board[nr][nc] <= 5:
                            score += 1
                            curr_d = change_dir[board[nr][nc]][curr_d]
                            curr_r, curr_c = nr, nc
                        
                        # D. 웜홀(6~10)을 만나는 경우
                        elif board[nr][nc] >= 6:
                            num = board[nr][nc]
                            # 현재 들어온 구멍이 pair1이면 pair2로, 아니면 pair1으로 순간이동
                            if (nr, nc) == wormholes[num]["pair1"]:
                                curr_r, curr_c = wormholes[num]["pair2"]
                            else:
                                curr_r, curr_c = wormholes[num]["pair1"]
                        
                        # E. 빈 공간(0)인 경우 그냥 직진
                        else:
                            curr_r, curr_c = nr, nc

        print(f"#{tc} {max_score}")