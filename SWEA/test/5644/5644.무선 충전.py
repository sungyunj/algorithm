# ------------------------------------------------------------------
#                           BC 1            BC 2            BC 3
# 위치 Location (X, Y)      (4, 4)          (7, 10)         (6, 3)

# 충전 범위 Coverage (C)        1               3               2

# 성능 Performance (P)        100             40              70
# ------------------------------------------------------------------


