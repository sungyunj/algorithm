# [그림 2]와 같이 사용자 A와 B의 이동 궤적이 주어졌다고 가정하자. T는 초(Second)를 의미한다. 
# 예를 들어 5초에 사용자 A는 (5, 2) 지점에, 사용자 B는 (6, 9) 지점에 위치한다.
# 매초마다 특정 BC의 충전 범위에 안에 들어오면 해당 BC에 접속이 가능하다. 
# 따라서 T=5에 사용자 A는 BC 3에, 사용자 B는 BC 2에 접속할 수 있다. 
# 이때, 접속한 BC의 성능(P)만큼 배터리를 충전 할 수 있다. 만약 한 BC에 두 명의 사용자가 접속한 경우, 접속한 사용자의 수만큼 충전 양을 균등하게 분배한다.

# BC의 정보와 사용자의 이동 궤적이 주어졌을 때, 모든 사용자가 충전한 양의 합의 최댓값을 구하는 프로그램을 작성하라.
 
# [그림 2]에서 T=11일 때, 사용자 A는 BC 1과 3 둘 중 하나에 접속이 가능하다. 
# 같은 시간에 사용자 B는 BC 1에 접속할 수 밖에 없다. 
# 따라서 사용자 A가 같은 BC 1에 접속한다면 충전되는 양를 반씩 나눠 갖게 되어 비효율적이다. 따라서 사용자 A가 BC 3에 접속하는 것이 더 이득이다.
 

# ------------------------------------------------------------------
#  T=11             사용자 A            사용자 B            충전량 합

# 접속한 BC          BC 1 (50)          BC 1 (50)         50 + 50 = 100
# (충전량)           BC 3 (70)          BC 1 (100)        70 + 100 = 170
# ------------------------------------------------------------------

# 위 예제에서 매 초마다 충전한 양은 다음과 같다. 따라서 총 충전한 양의 총합은 720 + 480 = 1200 이다.
 
