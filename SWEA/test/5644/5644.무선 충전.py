# [제약사항]
# 1. 지도의 가로, 세로 크기는 10이다.
# 2. 사용자는 총 2명이며, 사용자A는 지도의 (1, 1) 지점에서, 사용자B는 지도의 (10, 10) 지점에서 출발한다.
# 3. 총 이동 시간 M은 20이상 100이하의 정수이다. (20 ≤ M ≤ 100)
# 4. BC의 개수 A는 1이상 8이하의 정수이다. (1 ≤ A ≤ 8)
# 5. BC의 충전 범위 C는 1이상 4이하의 정수이다. (1 ≤ C ≤ 4)
# 6. BC의 성능 P는 10이상 500이하의 짝수이다. (10 ≤ P ≤ 500)
# 7. 사용자의 초기 위치(0초)부터 충전을 할 수 있다.
# 8. 같은 위치에 2개 이상의 BC가 설치된 경우는 없다. 그러나 사용자A, B가 동시에 같은 위치로 이동할 수는 있다. 사용자가 지도 밖으로 이동하는 경우는 없다.
 

# [입력]
# 입력의 맨 첫 줄에는 총 테스트 케이스의 개수 T가 주어지고, 그 다음 줄부터 T개의 테스트 케이스가 주어진다.
# 테스트 케이스의 첫 번째 줄에는 총 이동 시간(M), BC의 개수(A)가 주어진다.
# 그 다음 2개의 줄에는 각각 사용자 A와 B의 이동 정보가 주어진다.
# 한 사용자의 이동 정보는 M개의 숫자로 구성되며, 각각의 숫자는 다음과 같이 매초마다 이동 방향을 의미한다.
 

# ------------------------------------------------------------------
# 숫자             0              1            2             3                4

# 이동 방향     이동하지 않음       상 (UP)     우 (RIGHT)      하 (DOWN)       좌 (LEFT)
# ------------------------------------------------------------------


# 그 다음 줄에는 A개의 줄에 걸쳐 BC의 정보가 주어진다.
# 하나의 BC 정보는 좌표(X, Y), 충전 범위(C), 처리량(P)로 구성된다.

 
# [출력]
# 출력은 "#t"를 찍고 한 칸 띄운 다음 정답을 출력한다. (t는 테스트 케이스의 번호를 의미하며 1부터 시작한다.)
# 정답은 모든 사용자의 충전량 합의 최대값을 출력한다.


import sys
sys.stdin = open("/Users/tjddbsj/Desktop/github/algorithm/algorithm/SWEA/test/5644/sample_input.txt","r")

# 이동 방향: 정지, 상, 우, 하, 좌
dx = [0, 0, 1, 0, -1]
dy = [0, -1, 0, 1, 0]

def distance(x1, y1, x2, y2):
    return abs(x1 - x2) + abs(y1 - y2)

def solve():
    M, A = map(int, input().split()) # 이동 시간, BC 개수
    path_a = list(map(int, input().split()))
    path_b = list(map(int, input().split()))
    
    bcs = []
    for _ in range(A):
        # x, y, coverage, power
        bcs.append(list(map(int, input().split())))

    # 초기 위치 설정 (1,1) -> (0,0) index 조정 가능하지만 문제대로 1-based 사용 가능
    ax, ay = 1, 1
    bx, by = 10, 10
    
    total = 0

    # T=0부터 M까지 반복 (초기 위치 포함이므로 M+1번)
    for t in range(M + 1):
        # 1. 현재 위치에서 접속 가능한 BC 찾기
        avail_a = []
        avail_b = []
        
        for i in range(A):
            bc_x, bc_y, c, p = bcs[i]
            if distance(ax, ay, bc_x, bc_y) <= c:
                avail_a.append((i, p)) # BC 번호와 성능 저장
            if distance(bx, by, bc_x, bc_y) <= c:
                avail_b.append((i, p))
        
        # 2. 가능한 조합 중 최대 충전량 계산
        current_max = 0
        
        # 둘 다 접속 가능한 BC가 없는 경우 대비 빈 값 처리
        if not avail_a: avail_a.append((-1, 0))
        if not avail_b: avail_b.append((-1, 0))
        
        for idx_a, p_a in avail_a:
            for idx_b, p_b in avail_b:
                if idx_a == idx_b: # 같은 BC를 선택한 경우
                    # 나누어 갖든 말든 합계는 단일 BC의 성능과 같음 (P/2 + P/2 = P)
                    # 단, 둘 다 -1(없음)인 경우는 0
                    if idx_a == -1:
                        charge = 0
                    else:
                        charge = p_a 
                else: # 서로 다른 BC를 선택한 경우
                    charge = p_a + p_b
                
                current_max = max(current_max, charge)
        
        total += current_max
        
        # 3. 다음 위치로 이동 (마지막 t=M 일 때는 이동하지 않음)
        if t < M:
            ax += dx[path_a[t]]
            ay += dy[path_a[t]]
            bx += dx[path_b[t]]
            by += dy[path_b[t]]

    return total

T = int(input())
for t in range(1, T + 1):
    print(f"#{t} {solve()}")