# BC의 충전 범위가 C일 때, BC와 거리가 C 이하이면 BC에 접속할 수 있다. 이때, 두 지점 A(X_A, Y_A), B(X_B, Y_B) 사이의 거리는 다음과 같이 구할 수 있다.
# D = |X_A – X_B| + |Y_A – Y_B|
# 위의 [그림 1]에서 (4,3)과 (5,4) 지점은 BC 1과 BC 3의 충전 범위에 모두 속하기 때문에, 이 위치에서는 두 BC 중 하나를 선택하여 접속할 수 있다.

                       
