from collections import deque

# 1. 방향 정의: 상(0), 하(1), 좌(2), 우(3)
dr = [-1, 1, 0, 0]
dc = [0, 0, -1, 1]

# 2. 각 터널 타입별로 이동 가능한 방향 매핑
# 예: 2번은 상(0), 하(1)만 가능
pipe = {
    1: [0, 1, 2, 3],
    2: [0, 1],
    3: [2, 3],
    4: [0, 3],
    5: [1, 3],
    6: [1, 2],
    7: [0, 2]
}

# 3. 반대 방향 매핑 (연결 확인용)
# 내가 상(0)으로 가면 다음 칸에는 하(1)가 뚫려있어야 함
opp = {0: 1, 1: 0, 2: 3, 3: 2}

def bfs(r, c, L):
    # 시작점 방문 처리 및 큐 생성
    # (세로위치, 가로위치, 경과시간)
    q = deque([(r, c, 1)])
    visited = [[0] * M for _ in range(N)]
    visited[r][c] = 1
    count = 1  # 방문 가능한 지점 수
    
    while q:
        curr_r, curr_c, curr_time = q.popleft()
        
        # 탈주범이 L시간만큼만 이동 가능하므로, 
        # 현재 시간이 L이면 더 이상 주변을 탐색하지 않음
        if curr_time == L:
            continue
            
        curr_type = board[curr_r][curr_c]
        
        # 현재 위치의 터널 타입이 갈 수 있는 방향들 순회
        for d in pipe[curr_type]:
            nr = curr_r + dr[d]
            nc = curr_c + dc[d]
            
            # 지도 범위 안인가?
            if 0 <= nr < N and 0 <= nc < M:
                # 터널이 있고 아직 방문 전인가?
                if board[nr][nc] > 0 and not visited[nr][nc]:
                    next_type = board[nr][nc]
                    # ★핵심: 다음 터널이 현재 이동 방향과 연결되는 구조인가?
                    if opp[d] in pipe[next_type]:
                        visited[nr][nc] = 1
                        count += 1
                        q.append((nr, nc, curr_time + 1))
                        
    return count

